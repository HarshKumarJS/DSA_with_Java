// This program prints numbers from 1 to 50 using a while loop

public class while_loop {
    public static void main(String[] args) {

        // Initialize variable i with value 1
        int i = 1;

        // Continue looping as long as i is less than or equal to 50
        while (i <= 50) {
            // Print the current value of i
            System.out.println(i);

            // Increment i by 1 after each iteration
            i++;
        }
    }
}